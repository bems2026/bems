/** Forwards to the real bridge, stripping the proxy-only `token` query param first — the
 * bridge has no concept of it, and for GET history requests the *other* query params
 * (device_id, range) still need to pass through untouched. */
function proxyHttp(req, res, url) {
  const upstream = new URL(url);
  upstream.searchParams.delete('token');

  const proxyReq = http.request(
    { hostname: BRIDGE_HOST, port: BRIDGE_PORT, path: upstream.pathname + upstream.search, method: req.method, headers: { ...req.headers, host: `${BRIDGE_HOST}:${BRIDGE_PORT}` } },
    (proxyRes) => {
      // Node-RED's httpNodeCors already sends its own `access-control-*` headers (all
      // lowercase — Node always normalizes incoming header names). Spreading those
      // alongside our own CORS_HEADERS (capitalized keys) used to produce a response with
      // the SAME header twice under different casing — e.g. two Access-Control-Allow-Origin
      // values. That's invalid per the Fetch/CORS spec, and a browser rejects the response
      // outright with a fast, silent "Failed to fetch" — no server-side error, no slow
      // network involved. curl doesn't enforce CORS at all, so every curl-based check
      // during this bug's investigation looked fine; only a real browser could ever have
      // shown it. Strip the upstream's CORS headers before applying ours so exactly one
      // version of each survives.
      const headers = { ...proxyRes.headers };
      for (const key of Object.keys(headers)) {
        if (key.toLowerCase().startsWith('access-control-')) delete headers[key];
      }
      res.writeHead(proxyRes.statusCode, { ...headers, ...CORS_HEADERS });
      proxyRes.pipe(res);
    }
  );
  // A bridge that REFUSES a connection raises 'error' and is handled below. A bridge that
  // ACCEPTS and then hangs raises nothing at all, and without this timeout the request would
  // sit open indefinitely, holding a socket on both legs. Node-RED under a Tuya
  // discovery-retry storm is exactly the process that hangs rather than refuses — the
  // condition that produced ~104,500 journal lines an hour and needed
  // server/nodered-log-ratelimit.conf. The client's own abort would free the browser side,
  // but never this one.
  proxyReq.setTimeout(BRIDGE_TIMEOUT_MS, () => {
    proxyReq.destroy(new Error(`bridge did not respond within ${BRIDGE_TIMEOUT_MS}ms`));
  });

  proxyReq.on('error', (err) => {
    // The upstream detail goes to the journal, not to the caller. `String(err)` on a
    // Supabase or bridge error can carry project-identifying strings, and the caller has no
    // use for them — dispatchLight.mjs's 502 path already draws this line; the two
    // bridge-facing paths here did not.
    console.error(`[ibems-proxy] upstream ${req.method} ${upstream.pathname} failed: ${String(err)}`);
    // A hang that trips the timeout above may already have had headers written if the
    // bridge started responding and then stalled mid-body; there is no second status line
    // to send in that case, only a socket to close.
    if (res.headersSent) return res.destroy();
    sendJson(res, 502, { error: 'bridge_unreachable', detail: 'The Node-RED bridge did not respond.' });
  });
  req.pipe(proxyReq);
}

/**
 * `POST /api/command` — architecture plan Phase 6. `token` has already passed the generic
 * `isAuthorized` gate (so it's either a valid break-glass session or a valid Supabase
 * token) by the time this is called; this function applies the STRICTER rule commands
 * need on top of that.
 */
async function handleCommand(req, res, token) {
  // RM-157: how long the person waited, journaled once per command — the number the amber
  // "Switching" pulse makes visible, and the one the local-first record exists to shorten.
  const startedMs = Date.now();
  const session = await verifySupabaseSession(token, { fresh: true });
  if (!session.ok || !session.userId) {
    // isAuthorized() already accepted this token, so if it's not a real Supabase session
    // it must be a valid break-glass one — reject with a reason the frontend can render
    // distinctly from "not logged in at all" (401).
    return sendJson(res, 403, {
      error: 'break_glass_cannot_command',
      detail: 'Local/break-glass sessions are view-only — device commands require a real Supabase-authenticated session.',
    });
  }

  const body = await readJsonBody(req);
  // This building's own bounds — e.g. the minimum aircon setpoint the operator permits, which is
  // narrower than what the IR library can physically send. Read synchronously from the cache so a
  // command never waits on a round trip; `refresh()` runs in the background and, on failure,
  // leaves the last known floor in force rather than none. Read with this caller's session (RM-158).
  void livePolicy.refresh(false, { token });
  const validated = validateCommand(body, DEVICE_REGISTRY, livePolicy.current());
  if (!validated.ok) {
    return sendJson(res, validated.status, { error: validated.error, code: validated.code });
  }

  const { cmd } = validated;
  const device = DEVICE_REGISTRY.find((d) => d.id === cmd.device_id); // already validated to exist
  const swapped = await channelSwapRefusal(device, cmd);
  if (swapped) return sendJson(res, 409, swapped);
  const acceptedAtMs = Date.now();
  const ack = buildAck(cmd, acceptedAtMs);

  // The audit row is written with the CALLER's own token, not SUPABASE_ANON_KEY alone —
  // RLS's `auth.role() = 'authenticated'` check needs the request to actually carry a
  // signed-in user's session for PostgREST to grant the insert.
  const sbCommands = (path, init) =>
    fetch(`${SUPABASE_URL}/rest/v1/commands${path}`, {
      ...init,
      headers: { Authorization: `Bearer ${token}`, apikey: SUPABASE_ANON_KEY, 'Content-Type': 'application/json', ...init.headers },
      signal: AbortSignal.timeout(5000),
    });

  // Which classes really reach hardware is declared once, in dispatchLight.mjs, next to the
  // routing that implements it — so what /api/capabilities advertises and what this function
  // will actually do cannot drift apart. The record-then-act ordering is shared with
  // scheduler.mjs via auditedDispatch, so the two paths cannot disagree about what an
  // unrecorded command means: it is never dispatched.
  //
  // RM-157: recorded on the EDGE first, then uploaded once, after the relay has been asked.
  // The click used to wait for two Supabase round trips — the row before, the outcome after —
  // about 0.43 s each from here, and up to the 5 s timeout on a bad evening. See
  // `createLocalFirstAudit` and docs/adr/ADR-0014-commands-recorded-on-the-edge.md.
  const uploadRow = async (row) => {
    try {
      // `return=minimal`: nothing is patched afterwards, so no id is needed back.
      const res = await sbCommands('', { method: 'POST', headers: { Prefer: 'return=minimal' }, body: JSON.stringify(row) });
      if (!res.ok) return { ok: false, unreachable: !isRefusal(res.status), detail: `HTTP ${res.status} ${await res.text().catch(() => '')}` };
      return { ok: true };
    } catch (err) {
      return { ok: false, unreachable: true, detail: String(err) };
    }
  };
  const audit = createLocalFirstAudit({ inflightPath: COMMAND_INFLIGHT_PATH, bufferPath: COMMAND_BUFFER_PATH, upload: uploadRow });

  /**
   * A below-policy setpoint is RECORDED, not refused — RM-068.
   *
   * `validateCommand` used to return 400 `below_policy_floor` for these and the command never
   * happened, so there was nothing to record. Now it accepts and warns, which means the audit
   * trail is the only place the fact survives. Appending it to the note rather than adding a
   * column keeps it working on a database that has not been migrated for it, and the note is
   * already where this table carries prose.
   */
  const warningNote = (cmd.warnings ?? []).map((w) => w.detail).join('; ');

  const outcome = await auditedDispatch({
    device,
    cmd,
    note: warningNote ? `${ack.note} — ${warningNote}` : ack.note,
    auditRow: {
      command_id: cmd.command_id ?? null,
      device_id: cmd.device_id,
      socket: cmd.socket ?? null,
      action: cmd.action,
      target: cmd.target,
      requested_by: session.userId,
      accepted_at: new Date(acceptedAtMs).toISOString(),
      confirmed: false,
      confirmation: 'none',
      source: 'ibems-app',
      /**
       * Added ONLY for a capability write, and that is a sequencing decision rather than a
       * tidiness one. These two columns and `action = 'set'` arrive with
       * `supabase/phase29_command_capability.sql`, which is applied by hand. Naming a column
       * PostgREST does not have makes it reject the insert, so:
       *
       *   - a relay command's row is byte-identical to what it has always been, and cannot be
       *     broken by this change whether or not the migration has run;
       *   - a capability write before the migration fails at the AUDIT INSERT, and
       *     `auditedDispatch` refuses to dispatch anything it could not record first. The
       *     failure mode is a refused command, never an unrecorded one that moved hardware.
       *
       * So the write path is safe by construction until the migration lands, rather than safe
       * because someone remembered to apply it in the right order.
       */
      ...(cmd.action === 'set'
        ? { capability: cmd.capability, capability_value: cmd.value }
        : {}),
    },
    dispatchEnabled: HARDWARE_DISPATCH_ENABLED,
    dispatchClasses: DISPATCH_CLASSES,
    dispatch: (d, c) => dispatchCommand(d, c, {
      bridgeHost: BRIDGE_HOST,
      bridgePort: BRIDGE_PORT,
      lightApiToken: LIGHT_API_TOKEN,
      cloud: CLOUD_DISPATCH,
      // The site's own answer to "may a vendor be in this building's control path at all".
      // `local-first` (the default) is what this code has always done; `local-only` makes the
      // refusal explicit rather than relying on nobody having set the credentials.
      policy: DISPATCH_POLICY,
      readOnline: readDeviceOnline,
      // The aircon: its last commanded state fills a partial command, and an unverified local IR
      // library sends ON states through the cloud first. See dispatchLight.mjs `dispatchAircon`.
      readLatest: readDeviceLatest,
      localIrVerified: SITE.aircon?.local_ir_verified === true,
    }),
    insertAudit: audit.insertAudit,
    updateAudit: audit.updateAudit,
    log: (msg) => console.error(`[ibems-proxy] ${msg}`),
  });

  // The record goes up now, and the answer below does not wait for it. A failed upload is handed
  // to the outage queue inside `settle`, so this never rejects; it is only reported.
  if (outcome.auditId) {
    void audit.settle(outcome.auditId).then((settled) => {
      if (!settled.uploaded) console.error(`[ibems-proxy] command record kept on the edge for upload: ${settled.detail}`);
      // RM-159: the scheduler's aircon hold reads people's commands from the database, and no longer
      // re-reads it every minute. Told once the row is there, so its next read finds it.
      else signalConfigChanged('a command');
    });
  }

  // Audit completeness is part of Phase 6's DoD: no record, no command. A refusal here means the
  // edge could not write the record at all — nothing has touched hardware.
  if (outcome.auditFailure) {
    console.error(`[ibems-proxy] command audit record failed: ${outcome.auditFailure}`);
    return sendJson(res, 502, { error: 'audit_log_unreachable', detail: 'Could not record this command — refusing to proceed without an audit trail.' });
  }

  // The attempt is logged above (status:'failed', not silently omitted — an
  // attempted-and-failed command is exactly what a safety-critical audit trail exists to
  // capture) before this refusal, so the record survives even though the caller gets an
  // error rather than the ack.
  if (outcome.dispatchFailure) {
    // One code per failure MODE, not one code for "dispatch failed".
    //
    // Every one of these used to answer `hardware_dispatch_failed`, which the app rendered as
    // "The bridge did not accept the command (502)." So "the bridge reports THIS DEVICE
    // offline" — a fact about one socket, with a remedy at that socket — was indistinguishable
    // from the bridge being down. A physical test on 2026-08-31 reported exactly that
    // misreading as "bridge not reachable", while the bridge was serving readings throughout,
    // and it sent the diagnosis in the wrong direction for a fortnight.
    //
    // `detail` stays generic and names no host, port or upstream body: this response crosses
    // into a browser. The specifics are in the audit row and the journal.
    const FAILURE = {
      device_offline: {
        code: 'device_offline',
        detail: 'The bridge has no connection to this device, so the command could not reach it. The command was logged.',
      },
      bridge_unreachable: {
        code: 'bridge_unreachable',
        detail: 'The bridge could not be reached, so the command was not delivered. The command was logged.',
      },
      bridge_rejected: {
        code: 'bridge_rejected',
        detail: 'The bridge refused the command. The command was logged.',
      },
      no_route: {
        code: 'no_dispatch_route',
        detail: 'This deployment has no way to command a device of this kind. The command was logged.',
      },
      // Distinct from `no_dispatch_route`, and the difference is the remedy. That one means the
      // device cannot be commanded at all; this means SETTINGS have no LAN endpoint yet, so the
      // vendor cloud carries them — and it was not reachable either. An operator reading this
      // should check the internet, not the device.
      no_local_capability_route: {
        code: 'capability_needs_cloud',
        detail: 'Settings are sent through the vendor cloud until the bridge gains a local route for them, and the cloud could not be reached. The command was logged.',
      },
    };
    const mapped = FAILURE[outcome.dispatchReason] ?? {
      code: 'hardware_dispatch_failed',
      detail: 'The command was validated and logged, but the device did not actually respond — refusing to report it as accepted.',
    };
    console.log(`[ibems-proxy] command ${cmd.device_id} ${cmd.action} answered 502 ${mapped.code} in ${Date.now() - startedMs} ms`);
    return sendJson(res, 502, {
      error: mapped.code,
      code: mapped.code,
      detail: mapped.detail,
      // Which paths were tried. `none` means local AND the vendor cloud both failed, which is a
      // different situation from a deployment with no cloud configured at all — and the two
      // read identically without this.
      via: outcome.via ?? null,
    });
  }

  console.log(`[ibems-proxy] command ${cmd.device_id} ${cmd.action} answered ${ACCEPTED_STATUS} ${outcome.status} via ${outcome.via ?? '-'} in ${Date.now() - startedMs} ms`);
  res.writeHead(ACCEPTED_STATUS, { 'Content-Type': 'application/json', ...CORS_HEADERS });
  // `via` rides on the ack so the page can say HOW the command landed. A cloud-recovered
  // command is a success the operator would otherwise read as unremarkable, while it means the
  // device stopped answering locally — the earliest warning this system has that a device is
  // going bad. Null for a dry run, where no path was attempted.
  res.end(JSON.stringify({ ...ack, via: outcome.via ?? null }));
}

/**
 * What the journal hears about requests — RM-148, Stage 6. Every request used to be a line, and a
 * kiosk read is two (an OPTIONS and a GET): about 32,000 lines a day on 2026-09-29, which held the
 * persistent journal's 200 MB cap to five days of history instead of the ninety RM-125 set it up for.
 * Refusals, writes and upgrades are still logged as they happen; authorized reads are counted and
 * summarised once per interval, by path, so the traffic is still visible without drowning the rest.
 */
const LOG_SUMMARY_MS = Number(process.env.PROXY_LOG_SUMMARY_MS) || 10 * 60 * 1000;
const servedReads = new Map();
setInterval(() => {
  if (servedReads.size === 0) return;
  const total = [...servedReads.values()].reduce((a, n) => a + n, 0);
  const span = LOG_SUMMARY_MS >= 60_000 ? `${Math.round(LOG_SUMMARY_MS / 60_000)} min` : `${Math.round(LOG_SUMMARY_MS / 1000)} s`;
  console.log(`[ibems-proxy] served ${total} authorized read(s) in the last ${span}: ${[...servedReads].map(([p, n]) => `${p} ×${n}`).join(', ')}`);
  servedReads.clear();
}, LOG_SUMMARY_MS).unref();

const server = http.createServer(async (req, res) => {
  const url = new URL(req.url, `http://${req.headers.host}`);
  const origin = req.headers['origin'] || '-';

  if (req.method === 'OPTIONS') {
    res.writeHead(204, CORS_HEADERS);
    return res.end();
  }
  if (req.method === 'POST' && url.pathname === '/api/local-login') {
    console.log(`[ibems-proxy] POST /api/local-login origin=${origin}`);
    return handleLocalLogin(req, res);
  }

  const token = tokenFromRequest(req, url);
  const authorized = await isAuthorized(token);
  if (authorized && req.method === 'GET') {
    servedReads.set(url.pathname, (servedReads.get(url.pathname) ?? 0) + 1);
  } else {
    console.log(`[ibems-proxy] ${req.method} ${url.pathname} origin=${origin} token=${token ? token.slice(0, 12) + '…' : 'none'} -> ${authorized ? 'OK' : '401'}`);
  }
  if (!authorized) return sendJson(res, 401, { error: 'unauthorized' });

  if (req.method === 'GET' && url.pathname === '/api/tuya/devices') {
    // Always a 200 since 2026-09-17: the vendor cloud is one optional source (see DEVICE_SOURCES), and
    // `sources` says which of the three answered. A lapsed subscription used to take this whole list —
    // and so Add Device — down with it, while the devices and their imported keys were all still there.
    //
    // Which vendor devices already have a node. Read fresh rather than cached at startup: enrolling
    // one changes this, and a wizard showing a device it just added as still available is worse than
    // one extra read on a page nobody opens often.
    let flows = null;
    try {
      const auth = await createAdminClient({ host: '127.0.0.1', port: BRIDGE_PORT, timeoutMs: 10000 });
      ({ flows } = await auth.getFlows(await auth.login()));
    } catch (err) {
      // Reported, not swallowed. This read needs NODE_RED_ADMIN_USER/PASS, which nothing else here
      // does — so it fails independently, and on failure every `claimed` is false, which is
      // indistinguishable from an empty flow. The wizard then offers devices that already have a node
      // as available: a wrong list that looks right. That is exactly what happened when these keys
      // were missing from server/.env, and it stayed invisible because this catch was empty.
      // `claimed_known` lets the page say it does not know.
      console.error(`[ibems-proxy] claimed-set lookup failed, enrolment candidates unfiltered: ${err.message}`);
    }
    try {
      // Orphans are nodes whose device was re-paired under a new id — concluded cautiously, from LAN
      // silence AND a complete list without it; see deviceSources.mjs. Without the flow there are none.
      const listing = await DEVICE_SOURCES.listWithOrphans(flows ?? [], classForNode);
      if (listing.sources.cloud.status === 'unavailable') {
        console.warn(`[ibems-proxy] vendor cloud listing unavailable (${listing.sources.cloud.detail}); serving imported and LAN sources`);
      }
      return sendJson(res, 200, assertNoSecrets({
        devices: toPublicFleet(listing.devices, flows ? claimedNodesFrom(flows) : new Map()),
        claimed_known: flows !== null,
        orphan_nodes: listing.orphan_nodes,
        sources: listing.sources,
      }));
    } catch (err) {
      console.error(`[ibems-proxy] device listing failed: ${err.message}`);
      return sendJson(res, 500, { error: 'device_listing_failed' });
    }
  }
  if (req.method === 'GET' && url.pathname === '/api/credentials') {
    // What has been imported, without the keys: `publicView` carries each key's length only.
    return sendJson(res, 200, assertNoSecrets({ devices: CREDENTIAL_STORE.publicView() }));
  }
  if (req.method === 'POST' && url.pathname === '/api/credentials/import') {
    return handleCredentialImport(req, res);
  }
  if (req.method === 'GET' && url.pathname === '/api/tuya/presence') {
    // FI-015. Joins the cloud's per-device MAC against this host's ARP table, which is the one
    // diagnostic that separates "off the network, someone must drive to the office" from "on
    // the network but no longer discoverable, which is a config change". It existed only as
    // `npm run tuya:macs` — correct, but reachable solely over SSH, and the split it reports
    // moved twice inside an hour on 2026-08-26. A perishable answer that decides whether
    // somebody makes a journey should not require a terminal.
    const client = getTuyaClient();
    if (!client) return sendJson(res, 501, { error: 'tuya_not_configured' });
    try {
      const devices = await client.listDevices();
      const factoryInfos = await client.listFactoryInfos(devices.map((d) => d.id));
      // Unlike /api/tuya/devices this reads the HOST's neighbour table, so it means nothing
      // anywhere but the Pi. `readable` carries that: an empty table would otherwise be joined
      // into "every device is absent", which is the strongest claim available made from the
      // weakest evidence, and on screen would read as the whole fleet having left the network.
      const { readable, neighbours, reason } = readNeighbours();
      if (!readable) console.warn(`[ibems-proxy] /api/tuya/presence has no ARP view: ${reason}`);
      const rows = joinMacPresence({ cloudDevices: devices, factoryInfos, neighbours });
      return sendJson(res, 200, {
        arp_readable: readable,
        devices: toPublicPresence(rows, { arpReadable: readable }),
      });
    } catch (err) {
      // The upstream message can name the data centre and the account; log it, do not echo it.
      console.error(`[ibems-proxy] tuya presence fetch failed: ${err.message}`);
      return sendJson(res, 502, { error: 'tuya_unavailable' });
    }
  }
  if (req.method === 'GET' && url.pathname === '/api/capabilities') {
    // dispatch_classes is what the gate means in practice, not just whether it is open:
    // with the gate closed nothing dispatches, so the list is empty. The frontend uses it to
    // say which controls are live rather than going silent the moment the gate opens.
    // How many commands were recorded locally because Supabase could not be reached. A
    // command accepted into the buffer is not the same fact as one recorded in the audit
    // table, and the operator must not have to guess which they just did — this project's
    // whole posture is that the UI never claims more than it can observe.
    // RM-158: the policy is read with this caller's session; a break-glass one is not a database session.
    void livePolicy.refresh(false, { token: isValidLocalSession(token) ? undefined : token });
    return sendJson(res, 200, {
      hardware_dispatch_enabled: HARDWARE_DISPATCH_ENABLED,
      dispatch_classes: HARDWARE_DISPATCH_ENABLED ? DISPATCH_CLASSES : [],
      audit_buffer_pending: bufferCount(COMMAND_BUFFER_PATH) + bufferCount(SCHEDULER_BUFFER_PATH),
      // The site's declared policy, plus whether a vendor fallback is actually configured on
      // this deployment. Both, because they answer different questions and the page needs the
      // pair to say anything true: `local-first` with no credentials set behaves identically to
      // `local-only` today and is a completely different promise about tomorrow.
      dispatch_policy: DISPATCH_POLICY,
      cloud_fallback_configured: Boolean(CLOUD_DISPATCH?.client),
      // RM-038. The floor the NEXT command will actually be validated against, which is not
      // necessarily the one in the browser's bundle: an operator can change it without a
      // redeploy, and a setpoint selector built from a stale build value would offer a degree
      // that comes back as a 400 — which reads as a bug rather than as a policy.
      // RM-068: this number means the coldest ROOM TARGET now, not the coldest commandable
      // setpoint. Both keys are served for one release so a kiosk still running the pre-rename
      // bundle does not lose its value the moment phase35 lands.
      acu_min_room_target_c: roomTargetFloorC(livePolicy.current()),
      acu_min_setpoint_c: roomTargetFloorC(livePolicy.current()),
      // Where that number came from. A page reporting a floor it got from the build during a
      // database outage should be able to say so rather than presenting it as current.
      policy_source: livePolicy.status().source,
      // The aircon's two paths (2026-09-17). `acu_cloud_route` is whether a state the local IR
      // library cannot express (any mode but its own, any fan, swing) has anywhere to go:
      // ready | unconfigured | unresolved | local-only, or null with no aircon. The second is whether
      // somebody has watched the unit obey the local library since the hub was re-paired.
      acu_cloud_route: await acuCloudRoute(),
      acu_local_ir_verified: SITE.aircon?.local_ir_verified === true,
      // 2026-09-22: the protocol the flow generates frames in (`shared/irTcl112.mjs`), or null when it
      // can send only its captured library. With one, every state is sendable over the LAN.
      acu_local_ir_protocol: SITE.aircon?.ir_protocol ?? null,
    });
  }
  if (req.method === 'GET' && url.pathname === '/api/archive/status') {
    return handleArchiveStatus(res);
  }
  if (req.method === 'GET' && url.pathname === '/api/archive/readings') {
    return handleArchiveReadings(url, res);
  }
  if (req.method === 'GET' && url.pathname === '/api/archive/anomalies') {
    return handleArchiveAnomalies(url, res);
  }
  if (req.method === 'GET' && url.pathname === '/api/archive/trouble') {
    return handleArchiveTrouble(url, res);
  }
  if (req.method === 'GET' && url.pathname === '/api/archive/connectivity') {
    return handleArchiveConnectivity(url, res);
  }
  if (req.method === 'GET' && url.pathname === '/api/archive/buckets') {
    return handleArchiveBuckets(url, res);
  }
  if (req.method === 'POST' && url.pathname === '/api/config/changed') {
    // RM-159: the page saved a setting to Supabase; the scheduler reads it now rather than at its
    // next safety-net refresh. Moves nothing, so not behind HARDWARE_DISPATCH_ENABLED.
    signalConfigChanged('a setting saved in the app');
    return sendJson(res, 200, { ok: true });
  }
  if (req.method === 'POST' && url.pathname === '/api/enroll') {
    // Authenticated like every other route above. Deliberately NOT behind
    // HARDWARE_DISPATCH_ENABLED: that gate governs moving a relay, and enrolling a device
    // moves nothing. Conflating the two would mean a site that has not opened dispatch could
    // never add a device, which is backwards — you enrol before you switch.
    return handleEnroll(req, res, { readJsonBody, sendJson, token, sources: DEVICE_SOURCES });
  }
  if (req.method === 'POST' && url.pathname === '/api/rebind') {
    // Authenticated like enrolment and for the same reason not behind HARDWARE_DISPATCH_ENABLED:
    // it moves nothing. It points an orphaned node at the device that replaced it after a re-pair.
    return handleRebind(req, res, { readJsonBody, sendJson, token, sources: DEVICE_SOURCES });
  }
  if (req.method === 'POST' && url.pathname === '/api/remove') {
    // Same gate reasoning as enrolment, and the same authentication. Unlike enrolment this
    // needs no vendor cloud — removal reads the flow and the registry only, so it stays
    // available on a deployment with no Tuya credentials, which is also the deployment most
    // likely to need to undo something.
    return handleRemove(req, res, { readJsonBody, sendJson, token });
  }
  if (req.method === 'POST' && url.pathname === '/api/command') {
    return handleCommand(req, res, token);
  }

  proxyHttp(req, res, url);
});

// WebSocket relay: raw TCP, not a WS library — we never parse frames, just authenticate
// the handshake then pipe bytes both directions. Node-RED does the actual WS protocol
// work on the other end; this process only ever forwards.
server.on('upgrade', async (req, clientSocket, head) => {
  const url = new URL(req.url, `http://${req.headers.host}`);
  const token = tokenFromRequest(req, url);
  const authorized = await isAuthorized(token);
  console.log(`[ibems-proxy] WS upgrade ${url.pathname} origin=${req.headers['origin'] || '-'} token=${token ? token.slice(0, 12) + '…' : 'none'} -> ${authorized ? 'OK' : '401'}`);
  if (!authorized) {
    clientSocket.write('HTTP/1.1 401 Unauthorized\r\n\r\n');
    clientSocket.destroy();
    return;
  }

  const bridgeSocket = net.connect(BRIDGE_PORT, BRIDGE_HOST, () => {
    const upstream = new URL(url);
    upstream.searchParams.delete('token');
    const lines = [`GET ${upstream.pathname}${upstream.search} HTTP/1.1`];
    for (const [key, value] of Object.entries(req.headers)) {
      if (key.toLowerCase() === 'host') continue;
      lines.push(`${key}: ${value}`);
    }
    lines.push(`Host: ${BRIDGE_HOST}:${BRIDGE_PORT}`, '', '');
    bridgeSocket.write(lines.join('\r\n'));
    if (head?.length) bridgeSocket.write(head);
    bridgeSocket.pipe(clientSocket);
    clientSocket.pipe(bridgeSocket);
  });
  bridgeSocket.on('error', () => clientSocket.destroy());
  clientSocket.on('error', () => bridgeSocket.destroy());
});

server.listen(PROXY_PORT, () => {
  console.log(`[ibems-proxy] listening on :${PROXY_PORT}, forwarding authorized requests to ${BRIDGE_HOST}:${BRIDGE_PORT}`);
});

/**
 * Keep the offline verification keys current. Best-effort by design: a failure here is
 * ordinary (it is exactly what an outage looks like) and must never stop the proxy serving.
 * The keys already on disk stay valid, which is the entire point of persisting them.
 */
if (jwks) {
  const refreshJwks = async () => {
    const res = await jwks.refresh();
    if (res.ok) console.log(`[ibems-proxy] offline session keys refreshed (${res.count})`);
    else console.warn(`[ibems-proxy] could not refresh offline session keys (${res.detail}); using ${res.count} cached`);
  };
  refreshJwks();
  // unref: this timer must not hold the process open at shutdown.
  setInterval(refreshJwks, JWKS_REFRESH_MS).unref();
}

for (const sig of ['SIGTERM', 'SIGINT']) {
  process.on(sig, () => {
    console.log(`[ibems-proxy] received ${sig}, shutting down`);
    // server.close() alone stops accepting NEW connections but waits indefinitely for
    // existing ones to end on their own — a live WS relay (see the 'upgrade' handler
    // above) never closes by itself, so a browser with the dashboard open would leave
    // this hanging until systemd's stop timeout expired and SIGKILLed it (~90s of the
    // proxy being unreachable on every single restart — confirmed the hard way, see the
    // architecture plan's Phase 5 incident notes). closeAllConnections() forcibly ends
    // every socket the http.Server itself tracks, but measured ~27s to actually exit
    // with a real WS held open — an upgraded connection's *relayed* outbound leg (the
    // separate `net.connect()` to the bridge in the 'upgrade' handler) isn't one of
    // those tracked sockets, so something was still lingering. A hard timeout below
    // guarantees a prompt exit regardless of what closeAllConnections() does or doesn't
    // reach — don't trust the graceful path alone a second time without re-verifying.
    server.close(() => process.exit(0));
    server.closeAllConnections();
    setTimeout(() => process.exit(0), 2000);
  });
}
