// --- local (break-glass) sessions: opaque token -> expiry, in-memory only. Restarting
// this process invalidates every local session — acceptable for a rare, on-site fallback. ---
const localSessions = new Map();

function issueLocalSession() {
  const token = crypto.randomBytes(32).toString('hex');
  localSessions.set(token, Date.now() + LOCAL_SESSION_TTL_MS);
  return token;
}
function isValidLocalSession(token) {
  const exp = localSessions.get(token);
  if (!exp) return false;
  if (Date.now() > exp) {
    localSessions.delete(token);
    return false;
  }
  return true;
}
setInterval(() => {
  const now = Date.now();
  for (const [t, exp] of localSessions) if (now > exp) localSessions.delete(t);
}, 60_000).unref();

// --- Supabase sessions — RM-159: asked about online once per token, see sessionCheck.mjs ------

/**
 * Supabase's own answer about a token: `{answered: true, ok, userId}`, or `{answered: false}` when
 * the question could not be put — no answer at all, or one that does not judge the token. RM-157:
 * only a 4xx about the token is an answer. A project restricted for a quota answers 402, a rate
 * limit 429, an outage 5xx; none of them says this session is invalid, so they take the offline
 * path rather than a refusal that signs everybody out.
 */
async function askSupabaseAboutSession(token) {
  try {
    const res = await fetch(`${SUPABASE_URL}/auth/v1/user`, {
      headers: { Authorization: `Bearer ${token}`, apikey: SUPABASE_ANON_KEY },
      signal: AbortSignal.timeout(5000),
    });
    if (res.ok) {
      const body = await res.json();
      return { answered: true, ok: true, userId: typeof body?.id === 'string' ? body.id : null };
    }
    if (isRefusal(res.status)) return { answered: true, ok: false, userId: null };
    return { answered: false, detail: `auth answered ${res.status} without judging the token` };
  } catch (err) {
    return { answered: false, detail: String(err?.message ?? err) };
  }
}

const sessionCheck = createSessionCheck({
  askOnline: askSupabaseAboutSession,
  keys: () => (jwks ? jwks.keys() : []),
  refreshKeys: () => (jwks ? jwks.refresh() : null),
  issuer: JWKS_ISSUER,
  freshMs: SUPABASE_VERIFY_CACHE_MS,
  legacyCacheMs: SUPABASE_VERIFY_CACHE_MS,
  log: (line) => console.error(`[ibems-proxy] ${line}`),
});
setInterval(() => sessionCheck.sweep(), 60_000).unref();

/**
 * `{ok, userId, offline?}` — `userId` is `auth.users.id`, needed by `handleCommand` to attribute a
 * command's audit row to a real user. `fresh` is for commands: an online answer no older than a minute.
 */
function verifySupabaseSession(token, { fresh = false } = {}) {
  return sessionCheck.check(token, { fresh });
}

async function isAuthorized(token) {
  if (!token) return false;
  if (isValidLocalSession(token)) return true;
  return (await verifySupabaseSession(token)).ok;
}

function tokenFromRequest(req, url) {
  const header = req.headers['authorization'];
  if (header?.startsWith('Bearer ')) return header.slice(7);
  return url.searchParams.get('token') || null;
}

const CORS_HEADERS = {
  'Access-Control-Allow-Origin': '*',
  'Access-Control-Allow-Methods': 'GET, POST, OPTIONS',
  'Access-Control-Allow-Headers': 'content-type, authorization',
  'Access-Control-Max-Age': '600',
};

function sendJson(res, status, body) {
  res.writeHead(status, { 'Content-Type': 'application/json', ...CORS_HEADERS });
  res.end(JSON.stringify(body));
}

/**
 * RM-148: the edge's raw archive, READ-ONLY. The ingest daemon is its only writer; this process only
 * answers from it, for history older than the cloud's raw window (`shared/retention.mjs`). Opened on
 * first use and kept open — a WAL reader never blocks the writer — and dropped on any error so the
 * next request opens it afresh.
 */
const ARCHIVE_PATH = process.env.ARCHIVE_DB_PATH || join(dirname(fileURLToPath(import.meta.url)), 'data', 'archive', 'archive.sqlite');
/** A month plus a day: the longest report period, whichever way its window falls. One device's minutes for it are about 45,000 rows. */
const ARCHIVE_MAX_WINDOW_MS = 32 * 24 * 3600 * 1000;
let archiveReader = null;

function readArchive(fn) {
  try {
    archiveReader ??= openArchive(ARCHIVE_PATH, { readOnly: true });
    return fn(archiveReader);
  } catch (err) {
    try { archiveReader?.close(); } catch { /* reopened on the next request */ }
    archiveReader = null;
    throw err;
  }
}

function handleArchiveStatus(res) {
  try {
    const s = readArchive((a) => a.stats());
    return sendJson(res, 200, { available: true, oldest: s.oldest, newest: s.newest, readings: s.readings, bytes: s.bytes, hot_days: RAW_RETENTION_DAYS });
  } catch (err) {
    return sendJson(res, 200, { available: false, reason: String(err?.message ?? err).split(' — ')[0], hot_days: RAW_RETENTION_DAYS });
  }
}

/** One device's minute readings for a window, in the shape `src/lib/readingsExport.ts` exports. */
function handleArchiveReadings(url, res) {
  const deviceId = url.searchParams.get('device_id');
  const sinceMs = Date.parse(url.searchParams.get('since') ?? '');
  const untilMs = Date.parse(url.searchParams.get('until') ?? '');
  if (!deviceId || Number.isNaN(sinceMs) || Number.isNaN(untilMs) || untilMs <= sinceMs) {
    return sendJson(res, 400, { error: 'bad_window', detail: 'device_id, since and until (ISO instants, since before until) are required' });
  }
  if (untilMs - sinceMs > ARCHIVE_MAX_WINDOW_MS) {
    return sendJson(res, 400, { error: 'window_too_long', detail: 'at most 32 days of one device per request' });
  }
  let rows;
  try {
    rows = readArchive((a) => [...a.rowsBetween('readings', { sinceMs, untilMs, deviceId })]
      .map((r) => ({ ts: r.ts, voltage: r.voltage, current: r.current, power_w: r.power_w, energy_kwh_today: r.energy_kwh_today, online: r.online })));
  } catch (err) {
    return sendJson(res, 503, { error: 'archive_unavailable', detail: String(err?.message ?? err).split(' — ')[0] });
  }
  return sendJson(res, 200, { device_id: deviceId, rows });
}

/** A bell asks for minutes; a day is generous, and keeps one response small. */
const ANOMALY_MAX_WINDOW_MS = 24 * 60 * 60 * 1000;
const ANOMALY_COLUMNS = ['device_id', 'ts', 'metric', 'value', 'baseline_mean', 'baseline_stddev', 'z_score', 'iqr_lower', 'iqr_upper', 'method', 'sample_count'];

/**
 * `GET /api/archive/anomalies?since=<ISO>` — RM-158. The alert bell's recent anomalies, newest first,
 * in the columns `src/lib/supabaseAnomalies.ts` asks the cloud for.
 *
 * Every open browser asked Supabase this once a minute, and a browser asking Supabase sends a CORS
 * OPTIONS first: two lines in the project's log per minute per screen, about 2,880 a day for the
 * kiosk alone, when log ingestion was over the Free plan's 1 GB. Ingest archives each anomaly on the
 * edge the minute it finds it, before it uploads it, so the edge holds the same rows, sooner.
 */
function handleArchiveAnomalies(url, res) {
  const sinceMs = Date.parse(url.searchParams.get('since') ?? '');
  const nowMs = Date.now();
  if (Number.isNaN(sinceMs) || sinceMs > nowMs) {
    return sendJson(res, 400, { error: 'bad_window', detail: 'since (an ISO instant, not in the future) is required' });
  }
  if (nowMs - sinceMs > ANOMALY_MAX_WINDOW_MS) {
    return sendJson(res, 400, { error: 'window_too_long', detail: 'at most one day of anomalies per request' });
  }
  let rows;
  try {
    // A minute past now, so a row stamped by a clock slightly ahead of this one is not missed.
    rows = readArchive((a) => [...a.rowsBetween('anomalies', { sinceMs, untilMs: nowMs + 60_000 })]
      .map((r) => Object.fromEntries(ANOMALY_COLUMNS.map((c) => [c, r[c] ?? null]))));
  } catch (err) {
    return sendJson(res, 503, { error: 'archive_unavailable', detail: String(err?.message ?? err).split(' — ')[0] });
  }
  return sendJson(res, 200, { rows: rows.reverse() });
}

/** A week of trouble plus the day read before it (TROUBLE_FETCH_MS), and a day's slack. */
const TROUBLE_MAX_WINDOW_MS = 9 * 24 * 60 * 60 * 1000;

/** `since` as an instant not in the future and at most `maxMs` ago, or a 400 already sent. */
function windowSince(url, res, maxMs, label) {
  const sinceMs = Date.parse(url.searchParams.get('since') ?? '');
  const nowMs = Date.now();
  if (Number.isNaN(sinceMs) || sinceMs > nowMs) {
    sendJson(res, 400, { error: 'bad_window', detail: 'since (an ISO instant, not in the future) is required' });
    return null;
  }
  if (nowMs - sinceMs > maxMs) {
    sendJson(res, 400, { error: 'window_too_long', detail: label });
    return null;
  }
  return { sinceMs, nowMs };
}

function archiveUnavailable(res, err) {
  return sendJson(res, 503, { error: 'archive_unavailable', detail: String(err?.message ?? err).split(' — ')[0] });
}

/**
 * `GET /api/archive/trouble?since=<ISO>` — RM-159. The fault, power-warning and no-network minutes
 * `src/lib/supabaseCapabilityHistory.ts` asked the cloud for: three queries every five minutes from
 * every open screen, each with a CORS OPTIONS, about 1,700 lines a day in the project's log for the
 * kiosk alone. The edge holds every one of those minutes, sooner.
 */
function handleArchiveTrouble(url, res) {
  const w = windowSince(url, res, TROUBLE_MAX_WINDOW_MS, 'at most nine days of trouble per request');
  if (!w) return undefined;
  try {
    // A minute past now, as for the anomalies: a row stamped by a clock slightly ahead is not missed.
    return sendJson(res, 200, readArchive((a) => a.troubleRows({ sinceMs: w.sinceMs, untilMs: w.nowMs + 60_000, degradedNetStates: DEGRADED_NET_STATES })));
  } catch (err) {
    return archiveUnavailable(res, err);
  }
}

/**
 * `GET /api/archive/connectivity?hours=N` — RM-159. `device_connectivity` (supabase/phase15), which every
 * open screen called every five minutes for the flapping badge, over the edge's own minutes. Same clamp
 * (1..168 hours) and the same `expected_samples`.
 */
function handleArchiveConnectivity(url, res) {
  const asked = Number(url.searchParams.get('hours') ?? 24);
  const hours = Math.max(1, Number.isFinite(asked) ? Math.trunc(asked) : 24);
  // The archive is read on this process's one thread. A day takes about 140 ms on the Pi and a week about
  // 1.2 s (measured 2026-10-05), long enough to hold up a command. The app asks for a day; a longer window
  // is refused here, and the browser asks the cloud's `device_connectivity` instead.
  if (hours > CONNECTIVITY_MAX_HOURS) {
    return sendJson(res, 400, { error: 'window_too_long', detail: `at most ${CONNECTIVITY_MAX_HOURS} hours from the edge; ask the cloud for longer` });
  }
  const now = Date.now();
  // One answer a minute is shared: the bell and the Devices page, and every open screen, ask the same thing
  // every five minutes, and a day's figure does not move in a minute.
  if (!connectivityCache || connectivityCache.hours !== hours || now - connectivityCache.at >= CONNECTIVITY_CACHE_MS) {
    try {
      const rows = readArchive((a) => a.connectivity({ sinceMs: now - hours * 3600_000 }));
      connectivityCache = { hours, at: now, rows: rows.map((r) => ({ ...r, expected_samples: hours * 60 })) };
    } catch (err) {
      return archiveUnavailable(res, err);
    }
  }
  return sendJson(res, 200, { rows: connectivityCache.rows });
}

const CONNECTIVITY_MAX_HOURS = 48;
const CONNECTIVITY_CACHE_MS = 60_000;
let connectivityCache = null;

/** `readings_buckets`' own cap (supabase/phase9), so the edge refuses what the cloud would. */
const BUCKETS_MAX = 900;

/**
 * `GET /api/archive/buckets?device_id=&since=&bucket_s=` — RM-159. `readings_buckets` (phase9) for the
 * Analytics week: one device's minutes since `since`, averaged per bucket. Left open on that range, the
 * page asked the cloud once per device every five minutes — about 6,300 lines a day.
 */
function handleArchiveBuckets(url, res) {
  const deviceId = url.searchParams.get('device_id');
  const bucketSeconds = Number(url.searchParams.get('bucket_s'));
  if (!deviceId || !Number.isInteger(bucketSeconds) || bucketSeconds < 60) {
    return sendJson(res, 400, { error: 'bad_request', detail: 'device_id and bucket_s (whole seconds, at least 60) are required' });
  }
  const w = windowSince(url, res, ARCHIVE_MAX_WINDOW_MS, 'at most 32 days of one device per request');
  if (!w) return undefined;
  if (Math.ceil((w.nowMs - w.sinceMs) / 1000 / bucketSeconds) > BUCKETS_MAX) {
    return sendJson(res, 400, { error: 'too_many_buckets', detail: `over the ${BUCKETS_MAX}-bucket cap; use a larger bucket_s` });
  }
  try {
    return sendJson(res, 200, { device_id: deviceId, rows: readArchive((a) => a.buckets({ deviceId, sinceMs: w.sinceMs, untilMs: w.nowMs + 60_000, bucketSeconds })) });
  } catch (err) {
    return archiveUnavailable(res, err);
  }
}

async function readJsonBody(req) {
  let raw = '';
  for await (const chunk of req) raw += chunk;
  try {
    return JSON.parse(raw);
  } catch {
    return null;
  }
}

/**
 * `POST /api/credentials/import` — `{content, complete?}`, the text of a key-extraction tool's export.
 *
 * Authenticated like enrolment, and like enrolment not behind HARDWARE_DISPATCH_ENABLED: storing a
 * key moves nothing. The reply reports counts and per-row problems; it never carries a key, and the
 * problems name rows by name or id only (`credentialImport.mjs`).
 *
 * `complete` is the operator saying the export lists EVERY device in the account. Only then may a
 * device's absence from it count towards calling a flow node orphaned — see `deviceSources.mjs`.
 */
async function handleCredentialImport(req, res) {
  let raw = '';
  let size = 0;
  let oversize = false;
  // Drained to the end rather than cut off, so the client reads the 413 instead of a reset socket.
  for await (const chunk of req) {
    size += chunk.length;
    if (size > MAX_IMPORT_BODY_BYTES) oversize = true;
    else raw += chunk;
  }
  if (oversize) return sendJson(res, 413, { ok: false, problems: ['the export is larger than any device export should be'] });

  let body;
  try {
    body = JSON.parse(raw);
  } catch {
    return sendJson(res, 400, { ok: false, problems: ['malformed request body'] });
  }
  if (typeof body?.content !== 'string') return sendJson(res, 400, { ok: false, problems: ['content must be the export text'] });

  const parsed = parseCredentialExport(body.content);
  if (!parsed.format || parsed.devices.length === 0) {
    // `error` as well as `problems`: the browser's fetchJson surfaces only `error` from a non-2xx reply.
    const reason = parsed.problems[0] ?? 'no row had both a device id and a usable local key';
    return sendJson(res, 422, { ok: false, error: reason, format: parsed.format, added: 0, updated: 0, total: CREDENTIAL_STORE.publicView().length, complete: false, problems: parsed.problems.length ? parsed.problems : [reason] });
  }
  const complete = body.complete === true;
  const result = CREDENTIAL_STORE.importDevices(parsed.devices, { source: `import:${parsed.format}`, complete });
  console.log(`[ibems-proxy] credential import: ${parsed.devices.length} device(s), added ${result.added}, updated ${result.updated}, complete=${complete}, ${parsed.problems.length} problem(s)`);
  return sendJson(res, 200, assertNoSecrets({ ok: true, format: parsed.format, ...result, complete, problems: parsed.problems }));
}

