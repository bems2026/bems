#!/usr/bin/env node
/**
 * ibems-server authenticated proxy — architecture plan Phase 5, job 2 of 3 (job 1 is
 * `ingest.mjs`; job 3, the command gate, arrives closed-by-default in Phase 6).
 *
 * The only process besides Node-RED itself allowed to reach the bridge. Validates a
 * session before forwarding anything to `127.0.0.1:1880` — this is what actually enforces
 * the "do not port-forward 1880 / LAN only" warning already written into
 * docs/bridge-contract.md and docs/phase-f-runbook.md, instead of leaving it a
 * documentation-only convention. Fronted by `tailscale serve` for TLS on the tailnet;
 * reachable in plain HTTP on the LAN, same as this Pi's other services today — the auth
 * check applies on both paths equally, since network location was never meant to be the
 * security boundary here (see the architecture plan's Phase 5 access-model decision).
 *
 * Two ways to authenticate:
 *   1. Normal — a Supabase access token, `Authorization: Bearer <token>` on HTTP,
 *      `?token=<token>` on the WS upgrade (browsers can't set custom headers on a
 *      WebSocket handshake). Verified against Supabase's own `/auth/v1/user` endpoint,
 *      with a short local cache so a live session isn't re-verified against Supabase on
 *      every single request.
 *   2. Break-glass — `POST /api/local-login {password}` against a locally-hashed password
 *      (`BREAK_GLASS_PASSWORD_HASH` in server/.env, generated by
 *      `hashBreakGlassPassword.mjs`, plaintext never stored). For on-site access when
 *      Supabase Auth itself is unreachable. Issues an opaque, server-only session token —
 *      NOT a Supabase JWT, and not accepted by anything Supabase-side. The frontend must
 *      render this distinctly ("local session — LAN only, remote access unavailable"),
 *      never as an equivalent to a normal login — see src/stores/authStore.ts.
 */

import http from 'node:http';
import net from 'node:net';
import crypto from 'node:crypto';
import { URL } from 'node:url';
import { verifyBreakGlassPassword } from './breakGlass.mjs';

const PROXY_PORT = Number(process.env.PROXY_PORT) || 8080;
const BRIDGE_HOST = process.env.BRIDGE_HOST || '127.0.0.1';
const BRIDGE_PORT = Number(process.env.BRIDGE_PORT) || 1880;
const SUPABASE_URL = process.env.SUPABASE_URL;
// The ANON key, not service-role — verifying a user's own token needs no elevated
// privilege, and this process's whole point is to hold less power than ingest.mjs, not more.
const SUPABASE_ANON_KEY = process.env.VITE_SUPABASE_ANON_KEY || process.env.SUPABASE_ANON_KEY;
const BREAK_GLASS_PASSWORD_HASH = process.env.BREAK_GLASS_PASSWORD_HASH;
const SUPABASE_VERIFY_CACHE_MS = 60_000;
const LOCAL_SESSION_TTL_MS = 12 * 60 * 60 * 1000; // 12h

if (!SUPABASE_URL || !SUPABASE_ANON_KEY) {
  console.error('[ibems-proxy] SUPABASE_URL and VITE_SUPABASE_ANON_KEY are required — see server/.env.example');
  process.exit(1);
}
if (!BREAK_GLASS_PASSWORD_HASH) {
  console.warn('[ibems-proxy] BREAK_GLASS_PASSWORD_HASH not set — /api/local-login will 501 until it is (see server/hashBreakGlassPassword.mjs)');
}

// --- local (break-glass) sessions: opaque token -> expiry, in-memory only. Restarting
// this process invalidates every local session — acceptable for a rare, on-site fallback. ---
const localSessions = new Map();

function issueLocalSession() {
  const token = crypto.randomBytes(32).toString('hex');
  localSessions.set(token, Date.now() + LOCAL_SESSION_TTL_MS);
  return token;
}
function isValidLocalSession(token) {
  const exp = localSessions.get(token);
  if (!exp) return false;
  if (Date.now() > exp) {
    localSessions.delete(token);
    return false;
  }
  return true;
}
setInterval(() => {
  const now = Date.now();
  for (const [t, exp] of localSessions) if (now > exp) localSessions.delete(t);
}, 60_000).unref();

// --- Supabase token verification, cached briefly to avoid a round trip per request ------
const supabaseVerifyCache = new Map(); // token -> { validUntil, ok }

async function verifySupabaseToken(token) {
  const cached = supabaseVerifyCache.get(token);
  if (cached && Date.now() < cached.validUntil) return cached.ok;
  let ok;
  try {
    const res = await fetch(`${SUPABASE_URL}/auth/v1/user`, {
      headers: { Authorization: `Bearer ${token}`, apikey: SUPABASE_ANON_KEY },
      signal: AbortSignal.timeout(5000),
    });
    ok = res.ok;
  } catch {
    // Supabase unreachable — NOT the same fact as "invalid token". This proxy still
    // denies the request either way (fail closed), but it's exactly the condition under
    // which the frontend should offer the break-glass local-login path instead of just
    // retrying the same request.
    ok = false;
  }
  supabaseVerifyCache.set(token, { validUntil: Date.now() + SUPABASE_VERIFY_CACHE_MS, ok });
  return ok;
}

async function isAuthorized(token) {
  if (!token) return false;
  if (isValidLocalSession(token)) return true;
  return verifySupabaseToken(token);
}

function tokenFromRequest(req, url) {
  const header = req.headers['authorization'];
  if (header?.startsWith('Bearer ')) return header.slice(7);
  return url.searchParams.get('token') || null;
}

const CORS_HEADERS = {
  'Access-Control-Allow-Origin': '*',
  'Access-Control-Allow-Methods': 'GET, POST, OPTIONS',
  'Access-Control-Allow-Headers': 'content-type, authorization',
  'Access-Control-Max-Age': '600',
};

function sendJson(res, status, body) {
  res.writeHead(status, { 'Content-Type': 'application/json', ...CORS_HEADERS });
  res.end(JSON.stringify(body));
}

async function readJsonBody(req) {
  let raw = '';
  for await (const chunk of req) raw += chunk;
  try {
    return JSON.parse(raw);
  } catch {
    return null;
  }
}

async function handleLocalLogin(req, res) {
  if (!BREAK_GLASS_PASSWORD_HASH) return sendJson(res, 501, { error: 'break_glass_not_configured' });
  const body = await readJsonBody(req);
  const password = body?.password;
  if (!verifyBreakGlassPassword(password, BREAK_GLASS_PASSWORD_HASH)) {
    return sendJson(res, 401, { error: 'invalid_password' });
  }
  const token = issueLocalSession();
  sendJson(res, 200, { token, expires_in: LOCAL_SESSION_TTL_MS / 1000, mode: 'local' });
}

/** Forwards to the real bridge, stripping the proxy-only `token` query param first — the
 * bridge has no concept of it, and for GET history requests the *other* query params
 * (device_id, range) still need to pass through untouched. */
function proxyHttp(req, res, url) {
  const upstream = new URL(url);
  upstream.searchParams.delete('token');

  const proxyReq = http.request(
    { hostname: BRIDGE_HOST, port: BRIDGE_PORT, path: upstream.pathname + upstream.search, method: req.method, headers: { ...req.headers, host: `${BRIDGE_HOST}:${BRIDGE_PORT}` } },
    (proxyRes) => {
      // Node-RED's httpNodeCors already sends its own `access-control-*` headers (all
      // lowercase — Node always normalizes incoming header names). Spreading those
      // alongside our own CORS_HEADERS (capitalized keys) used to produce a response with
      // the SAME header twice under different casing — e.g. two Access-Control-Allow-Origin
      // values. That's invalid per the Fetch/CORS spec, and a browser rejects the response
      // outright with a fast, silent "Failed to fetch" — no server-side error, no slow
      // network involved. curl doesn't enforce CORS at all, so every curl-based check
      // during this bug's investigation looked fine; only a real browser could ever have
      // shown it. Strip the upstream's CORS headers before applying ours so exactly one
      // version of each survives.
      const headers = { ...proxyRes.headers };
      for (const key of Object.keys(headers)) {
        if (key.toLowerCase().startsWith('access-control-')) delete headers[key];
      }
      res.writeHead(proxyRes.statusCode, { ...headers, ...CORS_HEADERS });
      proxyRes.pipe(res);
    }
  );
  proxyReq.on('error', (err) => sendJson(res, 502, { error: 'bridge_unreachable', detail: String(err) }));
  req.pipe(proxyReq);
}

const server = http.createServer(async (req, res) => {
  const url = new URL(req.url, `http://${req.headers.host}`);
  const origin = req.headers['origin'] || '-';

  if (req.method === 'OPTIONS') {
    console.log(`[ibems-proxy] OPTIONS ${url.pathname} origin=${origin}`);
    res.writeHead(204, CORS_HEADERS);
    return res.end();
  }
  if (req.method === 'POST' && url.pathname === '/api/local-login') {
    console.log(`[ibems-proxy] POST /api/local-login origin=${origin}`);
    return handleLocalLogin(req, res);
  }

  const token = tokenFromRequest(req, url);
  const authorized = await isAuthorized(token);
  console.log(`[ibems-proxy] ${req.method} ${url.pathname} origin=${origin} token=${token ? token.slice(0, 12) + '…' : 'none'} -> ${authorized ? 'OK' : '401'}`);
  if (!authorized) return sendJson(res, 401, { error: 'unauthorized' });

  proxyHttp(req, res, url);
});

// WebSocket relay: raw TCP, not a WS library — we never parse frames, just authenticate
// the handshake then pipe bytes both directions. Node-RED does the actual WS protocol
// work on the other end; this process only ever forwards.
server.on('upgrade', async (req, clientSocket, head) => {
  const url = new URL(req.url, `http://${req.headers.host}`);
  const token = tokenFromRequest(req, url);
  const authorized = await isAuthorized(token);
  console.log(`[ibems-proxy] WS upgrade ${url.pathname} origin=${req.headers['origin'] || '-'} token=${token ? token.slice(0, 12) + '…' : 'none'} -> ${authorized ? 'OK' : '401'}`);
  if (!authorized) {
    clientSocket.write('HTTP/1.1 401 Unauthorized\r\n\r\n');
    clientSocket.destroy();
    return;
  }

  const bridgeSocket = net.connect(BRIDGE_PORT, BRIDGE_HOST, () => {
    const upstream = new URL(url);
    upstream.searchParams.delete('token');
    const lines = [`GET ${upstream.pathname}${upstream.search} HTTP/1.1`];
    for (const [key, value] of Object.entries(req.headers)) {
      if (key.toLowerCase() === 'host') continue;
      lines.push(`${key}: ${value}`);
    }
    lines.push(`Host: ${BRIDGE_HOST}:${BRIDGE_PORT}`, '', '');
    bridgeSocket.write(lines.join('\r\n'));
    if (head?.length) bridgeSocket.write(head);
    bridgeSocket.pipe(clientSocket);
    clientSocket.pipe(bridgeSocket);
  });
  bridgeSocket.on('error', () => clientSocket.destroy());
  clientSocket.on('error', () => bridgeSocket.destroy());
});

server.listen(PROXY_PORT, () => {
  console.log(`[ibems-proxy] listening on :${PROXY_PORT}, forwarding authorized requests to ${BRIDGE_HOST}:${BRIDGE_PORT}`);
});

for (const sig of ['SIGTERM', 'SIGINT']) {
  process.on(sig, () => {
    console.log(`[ibems-proxy] received ${sig}, shutting down`);
    // server.close() alone stops accepting NEW connections but waits indefinitely for
    // existing ones to end on their own — a live WS relay (see the 'upgrade' handler
    // above) never closes by itself, so a browser with the dashboard open would leave
    // this hanging until systemd's stop timeout expired and SIGKILLed it (~90s of the
    // proxy being unreachable on every single restart — confirmed the hard way, see the
    // architecture plan's Phase 5 incident notes). closeAllConnections() forcibly ends
    // every socket the http.Server itself tracks, but measured ~27s to actually exit
    // with a real WS held open — an upgraded connection's *relayed* outbound leg (the
    // separate `net.connect()` to the bridge in the 'upgrade' handler) isn't one of
    // those tracked sockets, so something was still lingering. A hard timeout below
    // guarantees a prompt exit regardless of what closeAllConnections() does or doesn't
    // reach — don't trust the graceful path alone a second time without re-verifying.
    server.close(() => process.exit(0));
    server.closeAllConnections();
    setTimeout(() => process.exit(0), 2000);
  });
}
