#!/usr/bin/env node
/**
 * ibems-server authenticated proxy — architecture plan Phase 5 (auth + proxy) and Phase 6
 * (the command gate, job 3 of 3 — job 1 is `ingest.mjs`).
 *
 * The only process besides Node-RED itself allowed to reach the bridge. Validates a
 * session before forwarding anything to `127.0.0.1:1880` — this is what actually enforces
 * the "do not port-forward 1880 / LAN only" warning already written into
 * docs/bridge-contract.md and docs/phase-f-runbook.md, instead of leaving it a
 * documentation-only convention. Fronted by `tailscale serve` for TLS on the tailnet;
 * reachable in plain HTTP on the LAN, same as this Pi's other services today — the auth
 * check applies on both paths equally, since network location was never meant to be the
 * security boundary here (see the architecture plan's Phase 5 access-model decision).
 *
 * Two ways to authenticate:
 *   1. Normal — a Supabase access token, `Authorization: Bearer <token>` on HTTP,
 *      `?token=<token>` on the WS upgrade (browsers can't set custom headers on a
 *      WebSocket handshake). Verified against Supabase's own `/auth/v1/user` endpoint,
 *      with a short local cache so a live session isn't re-verified against Supabase on
 *      every single request.
 *   2. Break-glass — `POST /api/local-login {password}` against a locally-hashed password
 *      (`BREAK_GLASS_PASSWORD_HASH` in server/.env, generated by
 *      `hashBreakGlassPassword.mjs`, plaintext never stored). For on-site access when
 *      Supabase Auth itself is unreachable. Issues an opaque, server-only session token —
 *      NOT a Supabase JWT, and not accepted by anything Supabase-side. The frontend must
 *      render this distinctly ("local session — LAN only, remote access unavailable"),
 *      never as an equivalent to a normal login — see src/stores/authStore.ts. It also
 *      cannot issue device commands (see `handleCommand` below) — there is no
 *      `auth.users` row to attribute a command to, and command audit rows require one.
 *
 * `POST /api/command` (Phase 6): validates via `shared/commands.mjs` (the same pure
 * contract the mock bridge uses), writes an audit row to Supabase's `commands` table using
 * the CALLER's own verified token — not this process's anon key alone, and never the
 * service-role key `ingest.mjs` holds — so RLS's `authenticated` policy is what actually
 * grants the insert, and `requested_by` is the real signed-in user. Dispatch itself stays
 * gated behind `HARDWARE_DISPATCH_ENABLED` (default unset/false): the ack is always
 * honest about what happened (`status: 'dry_run'` while closed).
 *
 * Phase 7 (lights only): with the gate open, a `switch`-class command is forwarded for
 * real to the live Node-RED flow's `POST /light/:id` (see `dispatchLightCommand`) — the
 * same entry point the physical node-red-dashboard UI already uses. Outlets and the ACU
 * have no equivalent endpoint and stay `dry_run` even with the gate open; building those
 * is separate, later work. `GET /api/capabilities` reports that asymmetry as
 * `dispatch_classes` so the UI can name which controls are actually live, rather than
 * treating an open gate as "everything on this page now moves hardware."
 */

import http from 'node:http';
import net from 'node:net';
import crypto from 'node:crypto';
import { URL } from 'node:url';
import { verifyBreakGlassPassword } from './breakGlass.mjs';
import { validateCommand, buildAck, ACCEPTED_STATUS } from '../shared/commands.mjs';
import { DEVICE_REGISTRY, TIMING } from '../shared/registry.mjs';

const PROXY_PORT = Number(process.env.PROXY_PORT) || 8080;
const BRIDGE_HOST = process.env.BRIDGE_HOST || '127.0.0.1';
const BRIDGE_PORT = Number(process.env.BRIDGE_PORT) || 1880;
const SUPABASE_URL = process.env.SUPABASE_URL;
// The ANON key, not service-role — verifying a user's own token needs no elevated
// privilege, and this process's whole point is to hold less power than ingest.mjs, not more.
const SUPABASE_ANON_KEY = process.env.VITE_SUPABASE_ANON_KEY || process.env.SUPABASE_ANON_KEY;
const BREAK_GLASS_PASSWORD_HASH = process.env.BREAK_GLASS_PASSWORD_HASH;
const SUPABASE_VERIFY_CACHE_MS = 60_000;
const LOCAL_SESSION_TTL_MS = 12 * 60 * 60 * 1000; // 12h
// Closed by default, mirroring node-red-bridge/deploy.mjs's --apply-only-with-explicit-
// intent pattern. Phase 7 is the only phase allowed to flip this in a real deployment.
const HARDWARE_DISPATCH_ENABLED = process.env.HARDWARE_DISPATCH_ENABLED === 'true';
// Shared secret with the live Node-RED flow's "Auth + validate" function (POST
// /light/:id) — see dispatchLightCommand below. Only ever needed when the gate above is
// open; local/mock-bridge dev never sets HARDWARE_DISPATCH_ENABLED, so this stays unset there.
const LIGHT_API_TOKEN = process.env.LIGHT_API_TOKEN || null;
// Reuses the exact constant this repo already defines for "how long a command gets
// before it's called failed" (shared/registry.mjs's TIMING, Stage 2/command-path
// comment) — not a new number invented for this one call.
const LIGHT_DISPATCH_TIMEOUT_MS = TIMING.COMMAND_TIMEOUT_MS;
// The device classes a command actually reaches hardware for. Lights are the only class with
// a real endpoint on the live flow (see dispatchLightCommand); outlets and the ACU have none
// and stay dry_run even with the gate open. Declared ONCE here and consumed by both
// handleCommand and GET /api/capabilities, so what the frontend is told and what the server
// will really do cannot drift apart — adding outlet dispatch later means adding its class
// here and its branch below, not hunting for a second hardcoded list.
const DISPATCH_CLASSES = ['switch'];

if (!SUPABASE_URL || !SUPABASE_ANON_KEY) {
  console.error('[ibems-proxy] SUPABASE_URL and VITE_SUPABASE_ANON_KEY are required — see server/.env.example');
  process.exit(1);
}
if (!BREAK_GLASS_PASSWORD_HASH) {
  console.warn('[ibems-proxy] BREAK_GLASS_PASSWORD_HASH not set — /api/local-login will 501 until it is (see server/hashBreakGlassPassword.mjs)');
}
// Hard fail-fast, not a warn-and-degrade like BREAK_GLASS_PASSWORD_HASH above: a proxy
// that believes it can dispatch to real hardware but has no way to authenticate to the
// light endpoint is a dangerous half-configuration, not a safe degraded mode.
if (HARDWARE_DISPATCH_ENABLED && !LIGHT_API_TOKEN) {
  console.error(
    '[ibems-proxy] HARDWARE_DISPATCH_ENABLED=true but LIGHT_API_TOKEN is unset — refusing to start. ' +
      'A hardware-dispatch-capable proxy with no way to authenticate to the light endpoint is a dangerous ' +
      'half-configuration, not a safe degraded mode. Set LIGHT_API_TOKEN in server/.env, or leave HARDWARE_DISPATCH_ENABLED unset/false.',
  );
  process.exit(1);
}

// --- local (break-glass) sessions: opaque token -> expiry, in-memory only. Restarting
// this process invalidates every local session — acceptable for a rare, on-site fallback. ---
const localSessions = new Map();

function issueLocalSession() {
  const token = crypto.randomBytes(32).toString('hex');
  localSessions.set(token, Date.now() + LOCAL_SESSION_TTL_MS);
  return token;
}
function isValidLocalSession(token) {
  const exp = localSessions.get(token);
  if (!exp) return false;
  if (Date.now() > exp) {
    localSessions.delete(token);
    return false;
  }
  return true;
}
setInterval(() => {
  const now = Date.now();
  for (const [t, exp] of localSessions) if (now > exp) localSessions.delete(t);
}, 60_000).unref();

// --- Supabase token verification, cached briefly to avoid a round trip per request ------
const supabaseVerifyCache = new Map(); // token -> { validUntil, ok, userId }

/** Returns `{ok, userId}` — `userId` is `auth.users.id`, needed by `handleCommand` to
 * attribute a command's audit row to a real user. Kept in the same cache entry as `ok`
 * rather than a second lookup, so a cached miss and a cached user id can never disagree. */
async function verifySupabaseSession(token) {
  const cached = supabaseVerifyCache.get(token);
  if (cached && Date.now() < cached.validUntil) return cached;
  let result = { ok: false, userId: null };
  try {
    const res = await fetch(`${SUPABASE_URL}/auth/v1/user`, {
      headers: { Authorization: `Bearer ${token}`, apikey: SUPABASE_ANON_KEY },
      signal: AbortSignal.timeout(5000),
    });
    if (res.ok) {
      const body = await res.json();
      result = { ok: true, userId: typeof body?.id === 'string' ? body.id : null };
    }
  } catch {
    // Supabase unreachable — NOT the same fact as "invalid token". This proxy still
    // denies the request either way (fail closed), but it's exactly the condition under
    // which the frontend should offer the break-glass local-login path instead of just
    // retrying the same request.
    result = { ok: false, userId: null };
  }
  supabaseVerifyCache.set(token, { ...result, validUntil: Date.now() + SUPABASE_VERIFY_CACHE_MS });
  return result;
}

async function isAuthorized(token) {
  if (!token) return false;
  if (isValidLocalSession(token)) return true;
  return (await verifySupabaseSession(token)).ok;
}

function tokenFromRequest(req, url) {
  const header = req.headers['authorization'];
  if (header?.startsWith('Bearer ')) return header.slice(7);
  return url.searchParams.get('token') || null;
}

const CORS_HEADERS = {
  'Access-Control-Allow-Origin': '*',
  'Access-Control-Allow-Methods': 'GET, POST, OPTIONS',
  'Access-Control-Allow-Headers': 'content-type, authorization',
  'Access-Control-Max-Age': '600',
};

function sendJson(res, status, body) {
  res.writeHead(status, { 'Content-Type': 'application/json', ...CORS_HEADERS });
  res.end(JSON.stringify(body));
}

async function readJsonBody(req) {
  let raw = '';
  for await (const chunk of req) raw += chunk;
  try {
    return JSON.parse(raw);
  } catch {
    return null;
  }
}

async function handleLocalLogin(req, res) {
  if (!BREAK_GLASS_PASSWORD_HASH) return sendJson(res, 501, { error: 'break_glass_not_configured' });
  const body = await readJsonBody(req);
  const password = body?.password;
  if (!verifyBreakGlassPassword(password, BREAK_GLASS_PASSWORD_HASH)) {
    return sendJson(res, 401, { error: 'invalid_password' });
  }
  const token = issueLocalSession();
  sendJson(res, 200, { token, expires_in: LOCAL_SESSION_TTL_MS / 1000, mode: 'local' });
}

/** Forwards to the real bridge, stripping the proxy-only `token` query param first — the
 * bridge has no concept of it, and for GET history requests the *other* query params
 * (device_id, range) still need to pass through untouched. */
function proxyHttp(req, res, url) {
  const upstream = new URL(url);
  upstream.searchParams.delete('token');

  const proxyReq = http.request(
    { hostname: BRIDGE_HOST, port: BRIDGE_PORT, path: upstream.pathname + upstream.search, method: req.method, headers: { ...req.headers, host: `${BRIDGE_HOST}:${BRIDGE_PORT}` } },
    (proxyRes) => {
      // Node-RED's httpNodeCors already sends its own `access-control-*` headers (all
      // lowercase — Node always normalizes incoming header names). Spreading those
      // alongside our own CORS_HEADERS (capitalized keys) used to produce a response with
      // the SAME header twice under different casing — e.g. two Access-Control-Allow-Origin
      // values. That's invalid per the Fetch/CORS spec, and a browser rejects the response
      // outright with a fast, silent "Failed to fetch" — no server-side error, no slow
      // network involved. curl doesn't enforce CORS at all, so every curl-based check
      // during this bug's investigation looked fine; only a real browser could ever have
      // shown it. Strip the upstream's CORS headers before applying ours so exactly one
      // version of each survives.
      const headers = { ...proxyRes.headers };
      for (const key of Object.keys(headers)) {
        if (key.toLowerCase().startsWith('access-control-')) delete headers[key];
      }
      res.writeHead(proxyRes.statusCode, { ...headers, ...CORS_HEADERS });
      proxyRes.pipe(res);
    }
  );
  proxyReq.on('error', (err) => sendJson(res, 502, { error: 'bridge_unreachable', detail: String(err) }));
  req.pipe(proxyReq);
}

/**
 * POSTs a real light command to the live Node-RED flow's `POST /light/:id` — the SAME
 * entry point the physical node-red-dashboard UI already uses (confirmed against the live
 * flow's own "Auth + validate" function node comment). Only ever called for
 * `device.class === 'switch'` commands while HARDWARE_DISPATCH_ENABLED is true — see
 * handleCommand's guard below. Outlets/ACU have no equivalent endpoint yet.
 *
 * Success/failure is decided purely on `res.ok` (HTTP 2xx), never on response body shape —
 * verified live that the flow's success response has no fixed envelope (its `response`
 * node's statusCode is unset, defaulting to 200, body is the full lights-state object) —
 * parsing that would couple this to an implementation detail with no contract behind it.
 * The body is only read, best-effort, for the failure-path `detail` string.
 *
 * Returns `{ok:true}` or `{ok:false, detail}` — never throws.
 */
async function dispatchLightCommand(device, cmd) {
  const lightId = parseInt(device.state_key.slice(1), 10); // 'L3' -> 3
  let res;
  try {
    res = await fetch(`http://${BRIDGE_HOST}:${BRIDGE_PORT}/light/${lightId}`, {
      method: 'POST',
      headers: { 'x-auth-token': LIGHT_API_TOKEN, 'Content-Type': 'application/json' },
      body: JSON.stringify({ state: cmd.action === 'on' }),
      signal: AbortSignal.timeout(LIGHT_DISPATCH_TIMEOUT_MS),
    });
  } catch (err) {
    return { ok: false, detail: `light endpoint unreachable: ${String(err)}` };
  }
  if (!res.ok) {
    const body = await res.text().catch(() => '');
    return { ok: false, detail: `light endpoint returned HTTP ${res.status}: ${body}` };
  }
  return { ok: true };
}

/**
 * `POST /api/command` — architecture plan Phase 6. `token` has already passed the generic
 * `isAuthorized` gate (so it's either a valid break-glass session or a valid Supabase
 * token) by the time this is called; this function applies the STRICTER rule commands
 * need on top of that.
 */
async function handleCommand(req, res, token) {
  const session = await verifySupabaseSession(token);
  if (!session.ok || !session.userId) {
    // isAuthorized() already accepted this token, so if it's not a real Supabase session
    // it must be a valid break-glass one — reject with a reason the frontend can render
    // distinctly from "not logged in at all" (401).
    return sendJson(res, 403, {
      error: 'break_glass_cannot_command',
      detail: 'Local/break-glass sessions are view-only — device commands require a real Supabase-authenticated session.',
    });
  }

  const body = await readJsonBody(req);
  const validated = validateCommand(body, DEVICE_REGISTRY);
  if (!validated.ok) {
    return sendJson(res, validated.status, { error: validated.error, code: validated.code });
  }

  const { cmd } = validated;
  const device = DEVICE_REGISTRY.find((d) => d.id === cmd.device_id); // already validated to exist
  const acceptedAtMs = Date.now();
  const ack = buildAck(cmd, acceptedAtMs);

  // Real dispatch is only attempted for `switch` (lights) — the only class with a real,
  // working endpoint on the live flow today (see dispatchLightCommand's header). Outlets
  // and the ACU stay 'dry_run' even with the gate open, on purpose: there is no equivalent
  // endpoint for them yet, and this is the ONE place that fact is encoded, so a future
  // outlet/ACU dispatch path is a one-line change here, not a rewrite of this function.
  let status = 'dry_run';
  let dispatchFailureDetail = null;
  if (HARDWARE_DISPATCH_ENABLED && DISPATCH_CLASSES.includes(device.class)) {
    const result = await dispatchLightCommand(device, cmd);
    if (result.ok) {
      status = 'dispatched';
    } else {
      status = 'failed';
      dispatchFailureDetail = result.detail;
      console.error(`[ibems-proxy] hardware dispatch failed for ${cmd.device_id}: ${result.detail}`);
    }
  }

  // The audit row is written with the CALLER's own token, not SUPABASE_ANON_KEY alone —
  // RLS's `auth.role() = 'authenticated'` check needs the request to actually carry a
  // signed-in user's session for PostgREST to grant the insert. Audit completeness is
  // part of Phase 6's DoD, so a failure here is NOT swallowed: no row, no command, even
  // though the command was otherwise valid — see the file header for why.
  try {
    const insertRes = await fetch(`${SUPABASE_URL}/rest/v1/commands`, {
      method: 'POST',
      headers: { Authorization: `Bearer ${token}`, apikey: SUPABASE_ANON_KEY, 'Content-Type': 'application/json', Prefer: 'return=minimal' },
      body: JSON.stringify({
        command_id: cmd.command_id ?? null,
        device_id: cmd.device_id,
        socket: cmd.socket ?? null,
        action: cmd.action,
        target: cmd.target,
        requested_by: session.userId,
        accepted_at: new Date(acceptedAtMs).toISOString(),
        confirmed: false,
        confirmation: 'none',
        note: ack.note,
        status,
        source: 'ibems-app',
      }),
      signal: AbortSignal.timeout(5000),
    });
    if (!insertRes.ok) {
      const detail = await insertRes.text();
      console.error(`[ibems-proxy] command audit insert failed: ${insertRes.status} ${detail}`);
      return sendJson(res, 502, { error: 'audit_log_unreachable', detail: 'Could not record this command — refusing to proceed without an audit trail.' });
    }
  } catch (err) {
    console.error('[ibems-proxy] command audit insert error:', err);
    return sendJson(res, 502, { error: 'audit_log_unreachable', detail: String(err) });
  }

  // The command is validated and logged above (status:'failed', not silently omitted — an
  // attempted-and-failed command is exactly what a safety-critical audit trail exists to
  // capture) before this refusal, so the record of the attempt survives even though the
  // caller gets an error rather than the ack.
  if (dispatchFailureDetail) {
    return sendJson(res, 502, {
      error: 'hardware_dispatch_failed',
      detail: 'The command was validated and logged, but the light did not actually respond — refusing to report it as accepted.',
    });
  }

  res.writeHead(ACCEPTED_STATUS, { 'Content-Type': 'application/json', ...CORS_HEADERS });
  res.end(JSON.stringify(ack));
}

const server = http.createServer(async (req, res) => {
  const url = new URL(req.url, `http://${req.headers.host}`);
  const origin = req.headers['origin'] || '-';

  if (req.method === 'OPTIONS') {
    console.log(`[ibems-proxy] OPTIONS ${url.pathname} origin=${origin}`);
    res.writeHead(204, CORS_HEADERS);
    return res.end();
  }
  if (req.method === 'POST' && url.pathname === '/api/local-login') {
    console.log(`[ibems-proxy] POST /api/local-login origin=${origin}`);
    return handleLocalLogin(req, res);
  }

  const token = tokenFromRequest(req, url);
  const authorized = await isAuthorized(token);
  console.log(`[ibems-proxy] ${req.method} ${url.pathname} origin=${origin} token=${token ? token.slice(0, 12) + '…' : 'none'} -> ${authorized ? 'OK' : '401'}`);
  if (!authorized) return sendJson(res, 401, { error: 'unauthorized' });

  if (req.method === 'GET' && url.pathname === '/api/capabilities') {
    // dispatch_classes is what the gate means in practice, not just whether it is open:
    // with the gate closed nothing dispatches, so the list is empty. The frontend uses it to
    // say which controls are live rather than going silent the moment the gate opens.
    return sendJson(res, 200, {
      hardware_dispatch_enabled: HARDWARE_DISPATCH_ENABLED,
      dispatch_classes: HARDWARE_DISPATCH_ENABLED ? DISPATCH_CLASSES : [],
    });
  }
  if (req.method === 'POST' && url.pathname === '/api/command') {
    return handleCommand(req, res, token);
  }

  proxyHttp(req, res, url);
});

// WebSocket relay: raw TCP, not a WS library — we never parse frames, just authenticate
// the handshake then pipe bytes both directions. Node-RED does the actual WS protocol
// work on the other end; this process only ever forwards.
server.on('upgrade', async (req, clientSocket, head) => {
  const url = new URL(req.url, `http://${req.headers.host}`);
  const token = tokenFromRequest(req, url);
  const authorized = await isAuthorized(token);
  console.log(`[ibems-proxy] WS upgrade ${url.pathname} origin=${req.headers['origin'] || '-'} token=${token ? token.slice(0, 12) + '…' : 'none'} -> ${authorized ? 'OK' : '401'}`);
  if (!authorized) {
    clientSocket.write('HTTP/1.1 401 Unauthorized\r\n\r\n');
    clientSocket.destroy();
    return;
  }

  const bridgeSocket = net.connect(BRIDGE_PORT, BRIDGE_HOST, () => {
    const upstream = new URL(url);
    upstream.searchParams.delete('token');
    const lines = [`GET ${upstream.pathname}${upstream.search} HTTP/1.1`];
    for (const [key, value] of Object.entries(req.headers)) {
      if (key.toLowerCase() === 'host') continue;
      lines.push(`${key}: ${value}`);
    }
    lines.push(`Host: ${BRIDGE_HOST}:${BRIDGE_PORT}`, '', '');
    bridgeSocket.write(lines.join('\r\n'));
    if (head?.length) bridgeSocket.write(head);
    bridgeSocket.pipe(clientSocket);
    clientSocket.pipe(bridgeSocket);
  });
  bridgeSocket.on('error', () => clientSocket.destroy());
  clientSocket.on('error', () => bridgeSocket.destroy());
});

server.listen(PROXY_PORT, () => {
  console.log(`[ibems-proxy] listening on :${PROXY_PORT}, forwarding authorized requests to ${BRIDGE_HOST}:${BRIDGE_PORT}`);
});

for (const sig of ['SIGTERM', 'SIGINT']) {
  process.on(sig, () => {
    console.log(`[ibems-proxy] received ${sig}, shutting down`);
    // server.close() alone stops accepting NEW connections but waits indefinitely for
    // existing ones to end on their own — a live WS relay (see the 'upgrade' handler
    // above) never closes by itself, so a browser with the dashboard open would leave
    // this hanging until systemd's stop timeout expired and SIGKILLed it (~90s of the
    // proxy being unreachable on every single restart — confirmed the hard way, see the
    // architecture plan's Phase 5 incident notes). closeAllConnections() forcibly ends
    // every socket the http.Server itself tracks, but measured ~27s to actually exit
    // with a real WS held open — an upgraded connection's *relayed* outbound leg (the
    // separate `net.connect()` to the bridge in the 'upgrade' handler) isn't one of
    // those tracked sockets, so something was still lingering. A hard timeout below
    // guarantees a prompt exit regardless of what closeAllConnections() does or doesn't
    // reach — don't trust the graceful path alone a second time without re-verifying.
    server.close(() => process.exit(0));
    server.closeAllConnections();
    setTimeout(() => process.exit(0), 2000);
  });
}
